# Client stall timers are finite: a 15 s cadence raced the observed ~15 s client tolerance.
KEEPALIVE_INTERVAL = 5.0
TRANSPORT_CHUNK_BYTES = 16384
# The runtime enforces the request deadline itself; the transport backstop trails it slightly
# so the runtime's own timeout response (or SSE error frame) is what clients normally see.
DEADLINE_GRACE_S = 1.0
# While a stream sends only heartbeats, note it in the log at this cadence.
STREAM_WAIT_LOG_INTERVAL_S = 30.0
HTTP_MESSAGES = {404: "route not found", 405: "method not allowed"}
logger = logging.getLogger("uvicorn.error")


def _route_kind(path: str) -> str:
    if path == "/v1/chat/completions":
        return "completion"
    if path == "/v1/models" or path.startswith("/v1/models/"):
        return "models"
    return "health" if path == "/healthz" else "other"


class RequestSummaryMiddleware:
    """Log transport metadata without buffering or exposing request/response content.

    Routes add outcome hints (metadata only: ids, counts, codes) to ``scope["relay.log"]``.
    """

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http" or not logger.isEnabledFor(logging.DEBUG):
            await self.app(scope, receive, send)
            return
        hints: dict[str, Any] = scope.setdefault("relay.log", {})
        method, path = scope["method"], scope["path"]
        started = time.monotonic()
        status: int | None = None
        response_bytes = 0
        complete = False
        logger.debug("request method=%r path=%r", method, path)

        async def tracked_send(message: Message) -> None:
            nonlocal status, response_bytes, complete
            await send(message)
            if message["type"] == "http.response.start":
                status = message["status"]
            elif message["type"] == "http.response.body":
                response_bytes += len(message.get("body", b""))
                complete = not message.get("more_body", False)

        try:
            await self.app(scope, receive, tracked_send)
        finally:
            kind = hints.pop("kind", None) or _route_kind(path)
            logger.debug(
                "response method=%r path=%r status=%s bytes=%d complete=%s duration_ms=%.1f "
                "kind=%s%s",
                method,
                path,
                status,
                response_bytes,
                complete,
                (time.monotonic() - started) * 1000,
                kind,
                "".join(f" {key}={value}" for key, value in hints.items()),
            )


class _GatewayApp(FastAPI):
    def build_middleware_stack(self) -> ASGIApp:
        # Observe error responses generated by Starlette's outer server-error middleware too.
        return RequestSummaryMiddleware(super().build_middleware_stack())


class JSONResponse(StarletteJSONResponse):
    """Bound transport buffering so admission also bounds slow-reader memory."""

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        await send(
            {"type": "http.response.start", "status": self.status_code, "headers": self.raw_headers}
        )
        for offset in range(0, len(self.body), TRANSPORT_CHUNK_BYTES):
            await send(
                {
                    "type": "http.response.body",
                    "body": self.body[offset : offset + TRANSPORT_CHUNK_BYTES],
                    "more_body": True,
                }
            )
        await send({"type": "http.response.body", "body": b"", "more_body": False})
        if self.background is not None:
            await self.background()


def _local(host: str | None) -> bool:
    if host == "localhost":
        return True
    try:
        return bool(host and ipaddress.ip_address(host).is_loopback)
    except ValueError:
        return False


class BoundaryMiddleware:
    """Authenticate and bound raw body bytes before routing or JSON decoding."""

    def __init__(self, app: ASGIApp, *, token: str, max_bytes: int, timeout_s: float) -> None:
        self.app, self.token, self.max_bytes = app, token, max_bytes
        self.timeout_s = timeout_s

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        # One budget from arrival covers the body read, the app and the runtime.
        deadline = time.monotonic() + self.timeout_s
        headers: dict[bytes, list[bytes]] = {}
        for key, value in scope["headers"]:
            headers.setdefault(key.lower(), []).append(value)
        error: GatewayError | None = None
        host = headers.get(b"host", [])
        try:
            parsed = urlsplit("//" + host[0].decode("ascii")) if len(host) == 1 else None
            if (
                (
                    parsed is None
                    or not _local(parsed.hostname)
                    or parsed.username is not None
                    or parsed.path
                    or parsed.query
                    or parsed.fragment
                )
                or parsed.port is not None
                and not 0 < parsed.port <= 65535
            ):
                error = GatewayError(400, "invalid loopback Host header")
        except (ValueError, UnicodeError):
            error = GatewayError(400, "invalid loopback Host header")
        origins = headers.get(b"origin", [])
        if origins:
            try:
                origin = urlsplit(origins[0].decode("ascii"))
                if (
                    len(origins) != 1
                    or origin.scheme not in {"http", "https"}
                    or not _local(origin.hostname)
                    or origin.username is not None
                    or origin.path
                    or origin.query
                    or origin.fragment
                ):
                    error = GatewayError(403, "non-local browser origin forbidden")
            except (ValueError, UnicodeError):
                error = GatewayError(403, "invalid browser origin")
        path = scope["path"]
        if path == "/v1" or path.startswith("/v1/"):
            auth = headers.get(b"authorization", [])
            expected = ("Bearer " + self.token).encode("utf-8")
            if len(auth) != 1 or not hmac.compare_digest(auth[0], expected):
                error = GatewayError(
                    401, "invalid authentication credentials", code="invalid_api_key"
                )
        if error:
            scope.setdefault("relay.log", {})["error_code"] = error.code or error.error_type
            response = JSONResponse(error.body(), status_code=error.status)
            await response(scope, receive, send)
            return
        body = bytearray()
        while True:
            try:
                message = await asyncio.wait_for(
                    receive(), timeout=max(0.001, deadline - time.monotonic())
                )
            except TimeoutError:
                response = JSONResponse(
                    GatewayError(504, "request body deadline exceeded").body(), status_code=504
                )
                await response(scope, receive, send)
                return
            if message["type"] == "http.disconnect":
                return
            body.extend(message.get("body", b""))
            if len(body) > self.max_bytes:
                response = JSONResponse(
                    GatewayError(413, "request body too large").body(), status_code=413
                )
                await response(scope, receive, send)
                return
            if not message.get("more_body", False):
                break
        delivered = False

        async def buffered_receive() -> Any:
            nonlocal delivered
            if not delivered:
                delivered = True
                return {"type": "http.request", "body": bytes(body), "more_body": False}
            return await receive()

        started = False
        is_sse = False
        at_boundary = True

        async def tracked_send(message: Any) -> None:
            nonlocal started, is_sse, at_boundary
            if message["type"] == "http.response.start":
                started = True
                is_sse = any(
                    key.lower() == b"content-type" and value.startswith(b"text/event-stream")
                    for key, value in message.get("headers", [])
                )
            chunk = message.get("body", b"") if message["type"] == "http.response.body" else b""
            if chunk:
                # Unknown until delivered: an interrupted send may be partially written.
                at_boundary = False
            await send(message)
            if chunk:
                at_boundary = chunk.endswith(b"\n\n")

        scope["relay.deadline"] = deadline
        try:
            async with asyncio.timeout(max(0.0, deadline + DEADLINE_GRACE_S - time.monotonic())):
                await self.app(scope, buffered_receive, tracked_send)
        except TimeoutError:
            failure = GatewayError(504, "request deadline exceeded", code="deadline_exceeded")
            scope.setdefault("relay.log", {})["error_code"] = failure.code
            if not started:
                await JSONResponse(failure.body(), status_code=504)(scope, receive, send)
            elif is_sse and at_boundary:
                # A slow/disconnected socket may also prevent delivery of this terminal error.
                with suppress(TimeoutError, OSError):
                    await asyncio.wait_for(
                        send(
                            {
                                "type": "http.response.body",
                                "body": event(failure.body()),
                                "more_body": False,
                            }
                        ),
                        timeout=1,
                    )
            else:
                # A partial non-streaming body, or an SSE frame cut mid-event, cannot be
                # terminated well-formed. Let the server close the incomplete HTTP transport.
                raise
        finally:
            cleanup = scope.get("relay.cleanup")
            if cleanup is not None:
                await cleanup()


def create_app(
    config: Config,
    *,
    token: str,
    limits: GatewayLimits | None = None,
    host: str = "127.0.0.1",
    adapters: Mapping[str, CompletionCapable] | None = None,
    catalog: ModelCatalog | None = None,
    runtime: GatewayRuntime | None = None,
    models: Sequence[str] | None = None,
    model_cache: ModelCache | None = None,
) -> FastAPI:
    """Build the gateway app; ``model_cache=None`` keeps discovered limits in memory only."""
    if not _local(host) or host == "localhost":
        raise ValueError("gateway listener must be a loopback IP address")
    if not token:
        raise ValueError("gateway token must not be empty")
    limits = limits or GatewayLimits(
        concurrency=config.defaults.concurrency, timeout_s=config.defaults.timeout_s
    )
    runtime = runtime or GatewayRuntime(
        limits,
        {
            name: agent.concurrency or config.defaults.concurrency
            for name, agent in config.agents.items()
        },
    )
    if adapters is None:
        adapters = default_adapters(config)
    # Non-billable inspect() profile checks are synchronous and happen once before the server
    # event loop. Billed model discovery is lazy: it starts on the first /v1/models request.
    catalog = catalog or ModelCatalog(config, adapters, models, model_cache)

    @asynccontextmanager
    async def lifespan(_app: FastAPI) -> AsyncGenerator[None]:
        try:
            yield
        finally:
            await catalog.close()
            await runtime.shutdown()

    app = _GatewayApp(docs_url=None, redoc_url=None, openapi_url=None, lifespan=lifespan)
    app.state.catalog, app.state.runtime = catalog, runtime
    app.add_middleware(
        BoundaryMiddleware,
        token=token,
        max_bytes=limits.max_request_bytes,
        timeout_s=limits.timeout_s,
    )

    @app.exception_handler(GatewayError)
    async def gateway_error(_request: Request, exc: GatewayError) -> JSONResponse:
        # Code only: error messages are never logged.
        _request.scope.setdefault("relay.log", {})["error_code"] = exc.code or exc.error_type
        headers = {"Retry-After": "1"} if exc.status == 429 else None
        return JSONResponse(exc.body(), status_code=exc.status, headers=headers)

    @app.exception_handler(CompletionError)
    async def completion_error(_request: Request, exc: CompletionError) -> JSONResponse:
        return await gateway_error(
            _request, GatewayError(exc.status, str(exc), exc.param, exc.code)
        )

    @app.exception_handler(HTTPException)
    async def http_error(_request: Request, exc: HTTPException) -> JSONResponse:
        # Fixed messages only: framework detail strings never cross the API boundary.
        try:
            message = HTTP_MESSAGES.get(exc.status_code) or HTTPStatus(exc.status_code).phrase
        except ValueError:
            message = "request failed"
        error = GatewayError(exc.status_code, message.lower())
        # Preserve framework headers such as Allow on 405 responses.
        return JSONResponse(error.body(), status_code=error.status, headers=exc.headers)

    @app.exception_handler(RequestValidationError)
    async def validation_error(_request: Request, _exc: RequestValidationError) -> JSONResponse:
        return await gateway_error(_request, GatewayError(400, "invalid request"))

    @app.exception_handler(Exception)
    async def internal_error(_request: Request, _exc: Exception) -> JSONResponse:
        return await gateway_error(
            _request,
            GatewayError(
                500, "internal gateway error", code="internal_error", error_type="server_error"
            ),
        )

    @app.get("/healthz")
    async def health() -> dict[str, str]:
        return {"status": "ok"}

    async def discover() -> None:
        # A quarantined gateway launches no further probes; it serves what is already known.
        if runtime.healthy:
            await catalog.discover(runtime)

    @app.get("/v1/models")
    async def list_models() -> dict[str, Any]:
        await discover()
        return catalog.listing()

    @app.get("/v1/models/{model_id:path}")
    async def get_model(model_id: str) -> dict[str, Any]:
        if model_id != "relay/auto" and model_id not in catalog.models:
            raise GatewayError(404, "unknown model", "model", "model_not_found")
        await discover()
        return catalog.public(model_id)

    @app.post("/v1/chat/completions")
    async def chat(request: Request) -> Response:
        started = time.monotonic()
        hints: dict[str, Any] = request.scope.setdefault("relay.log", {})
        try:
            payload = json.loads(
                await request.body(),
                parse_constant=lambda _: (_ for _ in ()).throw(ValueError("non-finite JSON")),
            )
        except (ValueError, UnicodeError, RecursionError) as exc:
            raise GatewayError(400, "invalid JSON request body") from exc
        parsed = parse_request(payload)
        schema = prepare_envelope(parsed)
        candidates = catalog.candidates(parsed)
        model = candidates[0]
        handle: CompletionHandle | None = None
        # Set before runtime.start: its task (and the worker thread) copy this context.
        completion_id, created = "chatcmpl-" + uuid.uuid4().hex, int(time.time())
        REQUEST_ID.set(completion_id)
        kind = f"{'stream' if parsed.stream else 'json'}+{'tools' if parsed.tools else 'plain'}"
        hints.update(kind=kind, id=completion_id)

        def validate(result: CompletionResult) -> CompletionResult:
            if schema is None:
                if result.content is None:
                    raise CompletionError("completion has no assistant text")
                try:
                    result.content.encode("utf-8", errors="strict")
                except UnicodeEncodeError as exc:
                    raise CompletionError("completion contains invalid Unicode") from exc
                return result
            raw = json.dumps(result.envelope) if result.envelope is not None else result.raw
            try:
                content, calls = validate_envelope(raw, parsed, schema)
            except EnvelopeError as exc:
                raise CompletionInvalid(str(exc), raw=raw, usage=result.usage) from exc
            return replace(
                result, content=content, envelope={"content": content, "tool_calls": calls}
            )

        # Share the budget computed at request arrival so the runtime's deadline expires first.
        deadline: float | None = request.scope.get("relay.deadline")
        timeout_s = None if deadline is None else max(0.001, deadline - time.monotonic())
        for model in candidates:
            effort = (
                parsed.reasoning_effort if parsed.reasoning_effort is not None else model.effort
            )
            observed = catalog.observed(model)
            context_limit = observed.context_length if observed is not None else None
            invocation = CompletionRequest(
                render_transcript(parsed, model.model, effort, context_limit=context_limit),
                model.model,
                effort,
                schema,
                parsed.output_tokens,
            )
            try:
                handle = runtime.start(
                    model.adapter, invocation, validate=validate, timeout_s=timeout_s
                )
            except CompletionError as exc:
                if exc.status != 429 or parsed.model != "relay/auto":
                    raise
                continue
            if logger.isEnabledFor(logging.DEBUG):
                # Metadata and counts only: never prompt text, tool schemas or descriptions.
                choice = parsed.tool_choice
                logger.debug(
                    "completion request kind=%s model=%s resolved=%s/%s effort=%s messages=%d "
                    "tools=%d tool_choice=%s response_format=%s prompt_bytes=%d",
                    kind,
                    parsed.model,
                    model.agent,
                    model.model,
                    effort,
                    len(parsed.messages),
                    len(parsed.tools or ()),
                    choice if isinstance(choice, str) else choice.type,
                    (parsed.response_format or {}).get("type", "none"),
                    len(invocation.prompt.encode("utf-8", "surrogatepass")),
                )
            break
        if handle is None:
            raise GatewayError(429, "completion capacity exhausted", code="rate_limit_exceeded")
        headers = {"X-Relay-Resolved-Model": f"{model.agent}/{model.model}"}
        ignored = [key for key in ("temperature", "top_p") if getattr(parsed, key) is not None]
        if ignored:
            headers["X-Relay-Ignored-Parameters"] = ", ".join(ignored)

        async def disconnected() -> None:
            while not await request.is_disconnected():
                await asyncio.sleep(0.05)
            handle.cancel()
            await handle.drain()

        watcher = asyncio.create_task(disconnected())

        async def cleanup() -> None:
            # A cancelled anyio scope (client disconnect) re-cancels every await; shield so
            # drain blocks on the worker instead of busy-spinning until it finishes.
            with anyio.CancelScope(shield=True):
                watcher.cancel()
                with suppress(asyncio.CancelledError):
                    await watcher
                if not handle.result.done():
                    handle.cancel()
                await handle.drain()

        request.scope["relay.cleanup"] = cleanup

        def outcome(result: CompletionResult) -> None:
            calls = len(result.envelope["tool_calls"]) if result.envelope else 0
            hints.update(
                finish_reason="tool_calls" if calls else result.finish_reason, tool_calls=calls
            )
            if result.usage is not None:
                hints.update(
                    prompt_tokens=result.usage.prompt_tokens,
                    completion_tokens=result.usage.completion_tokens,
                )

        def final(result: CompletionResult) -> dict[str, Any]:
            outcome(result)
            calls: list[dict[str, Any]] = result.envelope["tool_calls"] if result.envelope else []
            return completion_response(
                completion_id,
                created,
                parsed.model,
                result.content,
                calls,
                result.finish_reason,
                result.usage.as_openai() if result.usage else None,
            )

        if not parsed.stream:
            try:
                result = await asyncio.shield(handle.result)
                return JSONResponse(final(result), headers=headers)
            except BaseException:
                await cleanup()
                raise
        # Keep failures before the first keepalive or live chunk as ordinary HTTP errors.
        buffered: dict[str, Any] | None = None
        first_chunk: str | None = None
        chunk_task: asyncio.Task[str | None] | None = asyncio.create_task(handle.chunks.get())
        try:
            done, _pending = await asyncio.wait(
                {handle.result, chunk_task},
                timeout=KEEPALIVE_INTERVAL,
                return_when=asyncio.FIRST_COMPLETED,
            )
            if handle.result in done:
                if not chunk_task.done():
                    chunk_task.cancel()
                    with suppress(asyncio.CancelledError):
                        await chunk_task
                chunk_task = None
                result = handle.result.result()
                buffered = final(result)
            elif chunk_task in done:
                first_chunk = chunk_task.result()
                chunk_task = None
                if first_chunk is None:
                    result = await handle.result
                    buffered = final(result)
        except BaseException:
            if chunk_task is not None and not chunk_task.done():
                chunk_task.cancel()
                with suppress(asyncio.CancelledError):
                    await chunk_task
            await cleanup()
            raise

        # StreamingResponse is the sole consumer of disconnect notifications once
        # headers are handed to it; competing receive calls can lose disconnects.
        watcher.cancel()
        with suppress(asyncio.CancelledError):
            await watcher

        async def stream() -> AsyncIterator[bytes]:
            nonlocal chunk_task
            heartbeats = 0
            first_content_ms: int | None = None
            quiet_since = started
            include_usage = bool(parsed.stream_options and parsed.stream_options.include_usage)

            def Slice(data: bytes) -> Iterator[bytes]:
                for offset in range(0, len(data), TRANSPORT_CHUNK_BYTES):
                    yield data[offset : offset + TRANSPORT_CHUNK_BYTES]

            def first_content() -> str:
                return "false" if first_content_ms is None else str(first_content_ms)

            def delivering(*, live: bool) -> None:
                # Called before each content frame; restarts the heartbeat-only interval.
                nonlocal first_content_ms, quiet_since
                quiet_since = time.monotonic()
                if first_content_ms is None:
                    first_content_ms = round((quiet_since - started) * 1000)
                    hints["buffered"] = not live

            def waiting() -> None:
                # After each heartbeat: one INFO line per interval of heartbeat-only output.
                nonlocal quiet_since
                now = time.monotonic()
                if now - quiet_since >= STREAM_WAIT_LOG_INTERVAL_S:
                    quiet_since = now
                    logger.info(
                        "stream waiting heartbeats=%d elapsed_s=%.0f first_content=%s",
                        heartbeats,
                        now - started,
                        first_content(),
                    )

            try:
                if buffered is not None:
                    delivering(live=False)
                    for data in response_events(buffered, include_usage):
                        for piece in Slice(data):
                            yield piece
                    return

                role_sent = False
                if first_chunk is not None:
                    delivering(live=True)
                    for piece in Slice(
                        chunk_event(completion_id, created, parsed.model, {"role": "assistant"})
                    ):
                        yield piece
                    role_sent = True
                    for piece in Slice(
                        chunk_event(completion_id, created, parsed.model, {"content": first_chunk})
                    ):
                        yield piece

                while True:
                    if chunk_task is None:
                        chunk_task = asyncio.create_task(handle.chunks.get())
                    done, _pending = await asyncio.wait({chunk_task}, timeout=KEEPALIVE_INTERVAL)
                    if not done:
                        yield heartbeat_event(completion_id, created, parsed.model)
                        heartbeats += 1
                        waiting()
                        continue
                    item = chunk_task.result()
                    chunk_task = None
                    if item is None:
                        break
                    delivering(live=True)
                    if not role_sent:
                        for piece in Slice(
                            chunk_event(completion_id, created, parsed.model, {"role": "assistant"})
                        ):
                            yield piece
                        role_sent = True
                    for piece in Slice(
                        chunk_event(completion_id, created, parsed.model, {"content": item})
                    ):
                        yield piece

                result = await handle.result
                if not role_sent:
                    response = final(result)
                    delivering(live=False)
                    for data in response_events(response, include_usage):
                        for piece in Slice(data):
                            yield piece
                    return

                outcome(result)
                content = result.content or ""
                streamed = handle.streamed_content
                if content.startswith(streamed):
                    remainder = content[len(streamed) :]
                elif not streamed:
                    remainder = content
                else:
                    # Streamed text cannot be retracted; the final content diverged
                    # (e.g. after a repair retry), so the difference is not delivered.
                    logger.warning(
                        "streamed content diverged from final; dropping remainder "
                        "streamed_chars=%d final_chars=%d",
                        len(streamed),
                        len(content),
                    )
                    remainder = ""
                if remainder:
                    for piece in Slice(
                        chunk_event(completion_id, created, parsed.model, {"content": remainder})
                    ):
                        yield piece
                calls: list[dict[str, Any]] = (
                    result.envelope["tool_calls"] if result.envelope else []
                )
                for index, call in enumerate(format_tool_calls(completion_id, calls)):
                    for piece in Slice(
                        chunk_event(
                            completion_id,
                            created,
                            parsed.model,
                            {"tool_calls": [{"index": index, **call}]},
                        )
                    ):
                        yield piece
                finish = "tool_calls" if calls else result.finish_reason
                for piece in Slice(chunk_event(completion_id, created, parsed.model, {}, finish)):
                    yield piece
                if include_usage and result.usage is not None:
                    for piece in Slice(
                        usage_event(completion_id, created, parsed.model, result.usage.as_openai())
                    ):
                        yield piece
                yield b"data: [DONE]\n\n"
            except CompletionError as exc:
                hints["error_code"] = exc.code
                yield event(GatewayError(exc.status, str(exc), exc.param, exc.code).body())
            except asyncio.CancelledError:
                # Client went away (or the server is shutting down): attribute it, then let the
                # cancellation propagate so `finally` still drains the handle and releases the slot.
                logger.debug(
                    "completion stream cancelled by client heartbeats=%d elapsed_s=%.0f "
                    "first_content=%s",
                    heartbeats,
                    time.monotonic() - started,
                    first_content(),
                )
                raise
            except Exception as exc:
                # Unexpected backend failure: terminate the stream with a protocol-visible error
                # frame instead of truncating it. Only the exception type is logged; messages can
                # carry private prompt/completion content.
                logger.error("completion stream failed: %s", type(exc).__name__)
                hints["error_code"] = "internal_error"
                yield event(
                    GatewayError(
                        500,
                        "internal gateway error",
                        code="internal_error",
                        error_type="server_error",
                    ).body()
                )
            finally:
                hints.update(
                    heartbeats=heartbeats,
                    first_content_ms="none" if first_content_ms is None else first_content_ms,
                )
                if chunk_task is not None and not chunk_task.done():
                    chunk_task.cancel()
                    with suppress(asyncio.CancelledError):
                        await chunk_task
                await cleanup()

        return StreamingResponse(
            stream(),
            media_type="text/event-stream",
            headers={**headers, "Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
        )

    return app
